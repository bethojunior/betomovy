<?php

namespace App\Models\Trip\ChatTrip;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Str;

class MessagesChatTrip extends Model
{
    protected $table = 'messagesChatTrip';

    protected $primaryKey = 'idMessagesChatTrip';

    public $incrementing = false;

    protected $keyType = 'string';

    const CREATED_AT = 'date';
    const UPDATED_AT =  null;

    protected $fillable = [
        'message', 'userId', 'chatTripId',
    ];

    protected static function boot()
    {
        parent::boot(); // TODO: Change the autogenerated stub

        static::saving(function ($messageChatTrip){
            $messageChatTrip->{$messageChatTrip->getKeyName()} = (string) Str::uuid();
        });
    }

    public function chatTrip()
    {
        return $this->belongsTo(ChatTrip::class, 'chatTripId');
    }
}
