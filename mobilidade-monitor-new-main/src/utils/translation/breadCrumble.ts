export function breadCrumble(): { [key: string]: string };
export function breadCrumble(key: string): string;
export function breadCrumble(key?: string): string | { [key: string]: string } {
  const currentLang = getCurrentLanguage();
  const translations = currentLang === 'en' ? enTranslations : ptTranslations;

  if (key && typeof key === 'string') {
    const lowerKey = key.toLowerCase();
    return translations[lowerKey] || key;
  }

  return translations;
}